"""Generate ddev-sync's logo assets as pure paths.

Run it from the repository root with the font unpacked beside it:

    gh release download v2.304 --repo JetBrains/JetBrainsMono \\
        --pattern "JetBrainsMono-2.304.zip"
    unzip -q JetBrainsMono-2.304.zip -d jbm
    uv run --with fonttools python assets/make_logo.py

The font is not vendored: only the outlines of the glyphs used here end up in
the SVGs, and JetBrains Mono is SIL OFL, which those derived outlines carry
no obligation to redistribute.

Design §2.1: the NoiXdev brand X in cyan with a circular download badge in
the lower right, on the dark brand tile, plus a `ddev-`/`sync` wordmark
lockup. The glyphs are converted to outlines rather than referenced by
`font-family`, because the org's existing brand SVGs do the latter and
render wrong on any machine without JetBrains Mono installed.
"""

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

BASE, ACCENT, TEXT = "#0E1117", "#00E5FF", "#F2F4F8"
CAP = 730  # the X's own height in font units, measured from its outline
SPACING = -40  # the org wordmark's letter-spacing, scaled from its -20 at 500

font = TTFont("jbm/fonts/ttf/JetBrainsMono-ExtraBold.ttf")
glyphs, cmap, hmtx = font.getGlyphSet(), font.getBestCmap(), font["hmtx"]


def glyph_paths(text: str, spacing: float = 0.0) -> tuple[list[str], float]:
    out, x = [], 0.0
    for ch in text:
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs)
        glyphs[name].draw(pen)
        if d := pen.getCommands():
            out.append(f'<path transform="translate({x:.0f} 0)" d="{d}"/>')
        x += hmtx[name][0] + spacing
    return out, x - (spacing if text else 0)


def group(
    text: str, *, fill: str, scale: float, tx: float, baseline: float, spacing: float = 0.0
) -> tuple[str, float]:
    """A <g> whose paths sit on `baseline`, in SVG coordinates."""
    paths, advance = glyph_paths(text, spacing)
    body = "".join(paths)
    g = (
        f'  <g fill="{fill}" transform="translate({tx:.2f} {baseline:.2f}) '
        f'scale({scale:.5f} -{scale:.5f})">{body}</g>'
    )
    return g, advance * scale


# --- the tile ---------------------------------------------------------------
SIZE = 256
x_scale = 150 / CAP  # the X stands 150px tall on a 256 tile
_, x_width = glyph_paths("X")
x_width *= x_scale
x_group, _ = group(
    "X", fill=ACCENT, scale=x_scale, tx=(SIZE - x_width) / 2, baseline=(SIZE + 150) / 2
)

# The badge: a cyan disc with a dark download glyph. At 32px the arrow
# collapses into a cyan dot - a known trade-off the design accepts rather
# than shipping a second, size-specific asset.
bx, by, r = 196.0, 196.0, 42.0
badge = f"""  <g>
    <!-- A base-coloured disc one notch larger than the badge, so the X's leg
         reads as passing behind it rather than merging with it. Without the
         gap the two shapes fuse at favicon sizes, where the badge is already
         reduced to a dot. -->
    <circle cx="{bx}" cy="{by}" r="{r + 6}" fill="{BASE}"/>
    <circle cx="{bx}" cy="{by}" r="{r}" fill="{ACCENT}"/>
    <path fill="{BASE}" d="M{bx - 7} {by - 20}h14v16h11l-18 20-18-20h11z"/>
    <rect x="{bx - 19}" y="{by + 14}" width="38" height="7" rx="3.5" fill="{BASE}"/>
  </g>"""

tile = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}"
     width="{SIZE}" height="{SIZE}" role="img" aria-label="ddev-sync">
  <!-- Generated by assets/make_logo.py from JetBrains Mono ExtraBold (SIL OFL).
       Paths, not <text>: an asset that needs a font installed renders wrong
       everywhere it is not, which is the defect the org's other brand SVGs
       have. Tokens are NoiXdev's: {BASE} base, {ACCENT} accent, {TEXT} text. -->
  <rect width="{SIZE}" height="{SIZE}" fill="{BASE}"/>
{x_group}
{badge}
</svg>
"""

# --- the wordmark -----------------------------------------------------------
W, H, CAP_PX = 560, 160, 72
w_scale = CAP_PX / CAP
_, left_adv = glyph_paths("ddev-", SPACING)
_, right_adv = glyph_paths("sync", SPACING)
total = (left_adv + right_adv) * w_scale
start = (W - total) / 2
baseline = (H + CAP_PX) / 2

left, left_w = group(
    "ddev-", fill=TEXT, scale=w_scale, tx=start, baseline=baseline, spacing=SPACING
)
right, _ = group(
    "sync", fill=ACCENT, scale=w_scale, tx=start + left_w, baseline=baseline, spacing=SPACING
)

wordmark = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}"
     width="{W}" height="{H}" role="img" aria-label="ddev-sync">
  <!-- Generated by assets/make_logo.py from JetBrains Mono ExtraBold (SIL OFL).
       `ddev-` in {TEXT}, `sync` in {ACCENT}, mirroring how the org wordmark
       carries its accent on the X. Outlined for the same reason as logo.svg. -->
{left}
{right}
</svg>
"""

out = Path("/Users/noidee/_dev/ddev-sync/assets")
out.mkdir(exist_ok=True)
(out / "logo.svg").write_text(tile, encoding="utf-8")
(out / "logo-wordmark.svg").write_text(wordmark, encoding="utf-8")
print(f"logo.svg: X {x_width:.1f}px wide, badge r={r}")
print(f"logo-wordmark.svg: {total:.1f}px of glyphs, starting at x={start:.1f}")
print("no <text> element:", "<text" not in tile and "<text" not in wordmark)
