"""SQL expressions that turn a personal-data column into a stable fake value.

The values are generated by the local database itself, so a sanitize run is a
single UPDATE and never round-trips rows through Python. Every value is a pure
function of table, column and the row's key: the same row gets the same fake
value on every sync, which keeps a local copy diffable and bookmarks working.

This module is imported by `catalog.py`, so it must not import `catalog` or
`sanitize` (circular); the two tiny escaping helpers are therefore repeated
here with the same rules as catalog's `_identifier` and `_quote`.
"""

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from typing import Any

from ddev_sync.operations.base import OperationError
from ddev_sync.operations.fake_seeds import CITIES, FIRST_NAMES, LAST_NAMES, LOREM_WORDS

DEFAULT_EMAIL_DOMAIN = "example.fake"

# kind -> the settings it accepts. A kind absent from this mapping does not
# exist; a setting absent from its kind's set is a typo worth refusing loudly.
_ALLOWED_SETTINGS: dict[str, frozenset[str]] = {
    "name": frozenset(),
    "first_name": frozenset(),
    "last_name": frozenset(),
    "email": frozenset(),
    "text": frozenset({"length"}),
    "integer": frozenset({"min", "max"}),
    "zip": frozenset(),
    "city": frozenset(),
    "phone": frozenset(),
    "ip": frozenset({"version"}),
}
KINDS = frozenset(_ALLOWED_SETTINGS)

_DEFAULT_TEXT_LENGTH = 255  # the usual VARCHAR(255); a longer fake would be refused by strict mode
_EMAIL_SUFFIX_HEX = 12  # a unique email column needs more entropy than the 8 hex of other kinds
_SUFFIX_HEX = 8
_MIN_WORDS = 6
_MAX_WORDS = 14


@dataclass(frozen=True)
class FakeColumn:
    """One column of a `fake` rule: which column, what kind, with what settings."""

    column: str
    kind: str
    settings: Mapping[str, Any]


def _quote(value: str) -> str:
    """Escape a value for a single-quoted SQL literal (backslash first, then quote)."""
    return value.replace("\\", "\\\\").replace("'", "''")


def _identifier(value: str) -> str:
    """Escape a table or column name for backtick quoting."""
    return value.replace("`", "``")


def _is_int(value: Any) -> bool:
    # bool is an int subclass; `min: true` is a typo, not a number.
    return isinstance(value, int) and not isinstance(value, bool)


def _validate_settings(rule_name: str, column: str, kind: str, settings: Mapping[str, Any]) -> None:
    where = f"sanitize rule {rule_name!r}: column {column!r}"
    unknown = sorted(set(settings) - _ALLOWED_SETTINGS[kind])
    if unknown:
        raise OperationError(f"{where}: unknown setting {unknown[0]!r} for kind {kind!r}")
    if kind == "integer":
        if "min" not in settings or "max" not in settings:
            raise OperationError(f"{where}: kind 'integer' needs both 'min' and 'max'")
        low, high = settings["min"], settings["max"]
        if not _is_int(low) or not _is_int(high):
            raise OperationError(f"{where}: 'min' and 'max' must be integers")
        if low > high:
            raise OperationError(f"{where}: 'min' ({low}) is greater than 'max' ({high})")
    elif kind == "ip" and "version" in settings and settings["version"] not in (4, 6):
        raise OperationError(f"{where}: 'version' must be 4 or 6")
    elif kind == "text" and "length" in settings:
        length = settings["length"]
        if not _is_int(length) or length < 1:
            raise OperationError(f"{where}: 'length' must be an integer of at least 1")


def parse_columns(rule_name: str, raw: Any) -> list[FakeColumn]:
    """Validate a rule's `columns` mapping and return one `FakeColumn` per entry.

    Accepts `{col: "kind"}` and `{col: {type: kind, **settings}}`. All
    validation happens here, at parse time, so preflight can reject a bad rule
    before a production dump is downloaded.
    """
    if not isinstance(raw, Mapping) or not raw:
        raise OperationError(f"sanitize rule {rule_name!r}: 'columns' must be a non-empty mapping")
    columns: list[FakeColumn] = []
    for name, spec in raw.items():
        column = str(name)
        if isinstance(spec, Mapping):
            settings = {key: value for key, value in spec.items() if key != "type"}
            kind = spec.get("type")
        else:
            settings, kind = {}, spec
        if not isinstance(kind, str) or kind not in KINDS:
            raise OperationError(
                f"sanitize rule {rule_name!r}: column {column!r} has unknown kind {kind!r} "
                f"(known: {', '.join(sorted(KINDS))})"
            )
        _validate_settings(rule_name, column, kind, settings)
        columns.append(FakeColumn(column=column, kind=kind, settings=settings))
    return columns


def _draw(source: str, index: int) -> str:
    """An unsigned integer drawn from the hash input; `index` separates draws."""
    return f"CONV(LEFT(SHA2(CONCAT({source}, '#{index}'), 256), 8), 16, 10)"


def _pick(source: str, index: int, values: tuple[str, ...]) -> str:
    literals = ", ".join(f"'{_quote(value)}'" for value in values)
    return f"ELT(1 + {_draw(source, index)} % {len(values)}, {literals})"


def _capitalised(expression: str) -> str:
    return f"CONCAT(UPPER(LEFT({expression}, 1)), SUBSTRING({expression}, 2))"


def _text(source: str) -> str:
    """6-14 Lorem words, first capitalised, ending in a full stop."""
    parts = [_capitalised(_pick(source, 1, LOREM_WORDS))]
    parts += [f"' ', {_pick(source, i + 1, LOREM_WORDS)}" for i in range(1, _MIN_WORDS)]
    count = f"{_MIN_WORDS} + {_draw(source, 0)} % {_MAX_WORDS - _MIN_WORDS + 1}"
    for i in range(_MIN_WORDS, _MAX_WORDS):
        parts.append(f"IF({count} > {i}, CONCAT(' ', {_pick(source, i + 1, LOREM_WORDS)}), '')")
    return f"CONCAT({', '.join(parts)}, '.')"


def _realistic(kind: str, source: str, settings: Mapping[str, Any], domain: str) -> str:
    first = _pick(source, 0, FIRST_NAMES)
    last = _pick(source, 1, LAST_NAMES)
    generators: dict[str, Callable[[], str]] = {
        "first_name": lambda: first,
        "last_name": lambda: _pick(source, 0, LAST_NAMES),
        "city": lambda: _pick(source, 0, CITIES),
        "name": lambda: f"CONCAT_WS(' ', {first}, {last})",
        "email": lambda: (
            f"LOWER(CONCAT({first}, '.', {last}, '.', "
            f"LEFT(SHA2({source}, 256), {_EMAIL_SUFFIX_HEX}), '@{_quote(domain)}'))"
        ),
        "text": lambda: _text(source),
        "integer": lambda: (
            f"{settings['min']} + {_draw(source, 0)} % ({settings['max']} - {settings['min']} + 1)"
        ),
        "zip": lambda: f"LPAD(10000 + {_draw(source, 0)} % 89999, 5, '0')",
        "phone": lambda: f"CONCAT('+1 555 01', LPAD({_draw(source, 0)} % 100, 2, '0'))",
        "ip": lambda: (
            f"CONCAT('2001:db8::', LOWER(CONV(1 + {_draw(source, 0)} % 65534, 10, 16)))"
            if settings.get("version", 4) == 6
            else f"CONCAT('192.0.2.', 1 + {_draw(source, 0)} % 254)"
        ),
    }
    return generators[kind]()


def _masked(kind: str, source: str, settings: Mapping[str, Any], domain: str) -> str:
    """Constants (plus a short hash where uniqueness may matter) instead of seed lists."""
    short = f"LEFT(SHA2({source}, 256), {_SUFFIX_HEX})"
    long = f"LEFT(SHA2({source}, 256), {_EMAIL_SUFFIX_HEX})"
    values: dict[str, str] = {
        "name": f"CONCAT('Name ', {short})",
        "first_name": f"CONCAT('First ', {short})",
        "last_name": f"CONCAT('Last ', {short})",
        # Same 12-hex suffix as the realistic email: a unique email column must
        # stay collision-free in masked mode too.
        "email": f"CONCAT('user.', {long}, '@{_quote(domain)}')",
        "text": "'Lorem ipsum.'",
        "integer": str(settings.get("min", 0)),
        "zip": "'00000'",
        "city": "'City'",
        "phone": "'+1 555 0100'",
        "ip": "'2001:db8::'" if settings.get("version", 4) == 6 else "'192.0.2.0'",
    }
    return values[kind]


def value_sql(table: str, column: FakeColumn, key: str, *, email_domain: str, masked: bool) -> str:
    """The SQL expression that replaces one column's value.

    `NULL` and the empty string pass through unchanged: they carry meaning
    ("no email given") that code and tests locally depend on, and they hold no
    personal data to hide.
    """
    ident = _identifier(column.column)
    source = (
        f"CONCAT('{_quote(table)}.{_quote(column.column)}.', "
        f"LOWER(HEX(COALESCE(`{_identifier(key)}`, ''))))"
    )
    build = _masked if masked else _realistic
    generated = build(column.kind, source, column.settings, email_domain)
    if column.kind == "text":
        length = column.settings.get("length", _DEFAULT_TEXT_LENGTH)
        generated = f"LEFT({generated}, {length})"
    return f"CASE WHEN `{ident}` IS NULL THEN NULL WHEN `{ident}` = '' THEN '' ELSE {generated} END"
