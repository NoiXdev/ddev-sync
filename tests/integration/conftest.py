COMPOSE_NETWORK = "ddev-sync-integration_default"


def _run(argv: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        argv,
        capture_output=True,
        text=True,
        check=False,
        env={**os.environ, "DDEV_SYNC_PROJECT_DIR": str(PROJECT_DIR)},
    )


_BREW_OPT_CANDIDATES = (
    "/opt/homebrew/opt",
    "/usr/local/opt",
)
_BREW_CELLAR_CANDIDATES = (
    "/opt/homebrew/Cellar",
    "/usr/local/Cellar",
)


def _brew_bin_dir(formula: str) -> Path | None:
    """Find the `bin/` directory of a Homebrew formula, by formula name.

    The formula name and the binaries it installs are not always the same
    string - `mysql-client` installs `mysql`, `mysqladmin`, `mysqldump` and
    more, none of them named `mysql-client` - so this returns the directory
    rather than requiring a same-named binary inside it. Covers both the
    common case (`opt/<formula>/bin`, a symlink to whichever version is
    current) and the keg-only case (no `opt` link; only
    `Cellar/<formula>/<version>/bin` exists), which is how Homebrew ships
    `mysql-client` specifically to avoid clobbering the `mysql` formula's
    client libraries.
    """
    for root in _BREW_OPT_CANDIDATES:
        candidate = Path(root) / formula / "bin"
        if candidate.is_dir():
            return candidate
    for root in _BREW_CELLAR_CANDIDATES:
        versions = sorted(Path(root).glob(f"{formula}/*/bin"))
        if versions:
            return versions[-1]
    return None


@pytest.fixture(scope="session", autouse=True)
def gnu_rsync_on_path() -> Iterator[None]:
    """Make sure the `rsync` found on `PATH` understands `--info=progress2`.

    `transport/ssh.py` hardcodes that flag - a GNU rsync (>=3.1) feature.
    Every mainstream Linux distribution ships GNU rsync, so this is a no-op
    there; stock macOS ships `openrsync` instead, which rejects the flag
    outright. Preferring a Homebrew-installed GNU rsync, if one is present,
    closes exactly that gap without changing PATH resolution order for
    anything else; where Homebrew does not have it either, PATH is left
    alone and the real error surfaces normally rather than being silently
    skipped.
    """
    probe = _run(["rsync", "--info=progress2", "--version"])
    if probe.returncode == 0:
        yield
        return
    rsync_bin_dir = _brew_bin_dir("rsync")
    if (
        rsync_bin_dir is None
        or _run([str(rsync_bin_dir / "rsync"), "--info=progress2", "--version"]).returncode != 0
    ):
        yield
        return
    previous_path = os.environ.get("PATH", "")
    os.environ["PATH"] = f"{rsync_bin_dir}{os.pathsep}{previous_path}"
    try:
        yield
    finally:
        os.environ["PATH"] = previous_path


_MYSQL_WRAPPER_TEMPLATE = '''\
#!/usr/bin/env python3
"""Run `{entrypoint}` inside a throwaway container on the integration network.

Generated by tests/integration/conftest.py - not meant to be committed.

`operations/database.py` and `operations/sanitize.py` invoke a bare
`mysql`/`mysqladmin` against `--host=ddev-acme-db`. That hostname is a
Docker Compose network alias (see docker-compose.yaml's `local-db` service) -
visible to *other containers* on the same network, not to plain subprocess
commands running on the host, with no `/etc/hosts` edit involved. A real
DDEV project does not hit this: ddev-sync normally runs from inside the
project's own web container, already attached to that network. Running the
client itself inside a one-off container joined to the same network puts it
exactly there, without changing anything the tool does or needing elevated
privileges on the host.
"""

import subprocess
import sys

BASE_TEMP = {base_temp!r}
PROJECT_DIR = {project_dir!r}
NETWORK = {network!r}
IMAGE = "mariadb:11"


def main() -> int:
    command = [
        "docker", "run", "--rm",
        "--network", NETWORK,
        "-v", f"{{BASE_TEMP}}:{{BASE_TEMP}}",
        "-v", f"{{PROJECT_DIR}}:{{PROJECT_DIR}}",
        "--entrypoint", {entrypoint!r},
        IMAGE,
        *sys.argv[1:],
    ]
    return subprocess.run(command, check=False).returncode


if __name__ == "__main__":
    raise SystemExit(main())
'''

# `mariadb:11` does not ship the old `mysql`/`mysqladmin` names at all - only
# `mariadb` and `mariadb-admin`, which accept the identical options the tool
# passes. The wrapper script is still named `mysql`/`mysqladmin`, because
# that is the literal binary name `operations/database.py` and
# `operations/sanitize.py` exec; only the `--entrypoint` inside the
# container differs.
_MYSQL_ENTRYPOINTS = {"mysql": "mariadb", "mysqladmin": "mariadb-admin"}


@pytest.fixture(scope="session", autouse=True)
def dockerized_mysql_clients(tmp_path_factory: pytest.TempPathFactory) -> Iterator[None]:
    """Make the local `mysql` and `mysqladmin` reach `ddev-acme-db` by name.

    Installing a MariaDB/MySQL client locally (Linux CI images usually have
    one already; stock macOS has none) only solves half the problem: even
    with a real client binary, `--host=ddev-acme-db` still will not resolve
    from a bare host process, because that alias only exists on the Docker
    network the stack created - see `_MYSQL_WRAPPER_TEMPLATE` above for the
    full reasoning. Generating wrapper scripts that run the real client
    inside a throwaway container on that network, ahead of anything else on
    `PATH`, solves both gaps in one place, identically on macOS and Linux.
    `source <dump>` reads the dump from inside the project, which lives at
    `PROJECT_DIR`, so that directory is bind-mounted at its own path; the
    shared pytest base temp directory is mounted the same way for anything
    a test still keeps in `tmp_path`.
    """
    base_temp = tmp_path_factory.getbasetemp().resolve()
    bin_dir = HERE / ".keys" / "mysql-wrappers"
    bin_dir.mkdir(parents=True, exist_ok=True)
    for tool, entrypoint in _MYSQL_ENTRYPOINTS.items():
        script = bin_dir / tool
        script.write_text(
            _MYSQL_WRAPPER_TEMPLATE.format(
                base_temp=str(base_temp),
                project_dir=str(PROJECT_DIR),
                network=COMPOSE_NETWORK,
                entrypoint=entrypoint,
            ),
            encoding="utf-8",
        )
        script.chmod(0o755)
    previous_path = os.environ.get("PATH", "")
    os.environ["PATH"] = f"{bin_dir}{os.pathsep}{previous_path}"
    try:
        yield
    finally:
        os.environ["PATH"] = previous_path


