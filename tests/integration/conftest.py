@pytest.fixture(scope="session", autouse=True)
def ssh_agent(ssh_key: Path) -> Iterator[None]:
    """Run a dedicated `ssh-agent` for the session and load the throwaway key.

    `transport/ssh.py` builds a bare `ssh user@host ...` argv with no `-i` -
    deliberately, mirroring how DDEV's own `ddev auth ssh` relies on an agent
    rather than passing an identity file on every invocation. `IdentityFile`
    in a `~/.ssh/config` would have been the obvious alternative, but ssh
    resolves `~` for its config and known_hosts from the real UID's
    password-database home directory, not from the `HOME` environment
    variable - overriding `HOME` for the test process was tried first and
    silently did nothing. A dedicated agent is also the better match for
    what it is standing in for, and keeps the throwaway key out of whatever
    agent the developer normally runs.
    """
    started = _run(["ssh-agent", "-s"])
    if started.returncode != 0:
        pytest.fail(f"could not start a dedicated ssh-agent:\n{started.stderr}")
    agent_env: dict[str, str] = {}
    for line in started.stdout.splitlines():
        if line.startswith(("SSH_AUTH_SOCK=", "SSH_AGENT_PID=")):
            key, _, rest = line.partition("=")
            agent_env[key] = rest.split(";", 1)[0]
    previous = {key: os.environ.get(key) for key in agent_env}
    os.environ.update(agent_env)
    added = _run(["ssh-add", str(ssh_key)])
    if added.returncode != 0:
        pytest.fail(f"could not add the throwaway key to the dedicated agent:\n{added.stderr}")
    try:
        yield
    finally:
        pid = agent_env.get("SSH_AGENT_PID")
        if pid is not None:
            _run(["kill", pid])
        for key, value in previous.items():
            if value is not None:
                os.environ[key] = value
            else:
                os.environ.pop(key, None)


