@pytest.fixture(scope="session", autouse=True)
def stack(ssh_key: Path, remote_layout: Path) -> Iterator[None]:
    """Start the containers, wait for readiness, tear down afterwards.

    Neither `linuxserver/openssh-server` nor `mariadb:11` ships a built-in
    `HEALTHCHECK`, so without the ones added in `docker-compose.yaml`,
    `--wait` has nothing to wait on and reports every container "healthy"
    the instant it starts - before sshd is listening, before the mysql
    client mod has finished installing, and before MariaDB has replayed
    `seed.sql`. The healthchecks make `--wait` block on the real thing.
    """
    if _run(["docker", "info"]).returncode != 0:
        pytest.skip("docker is not available")
    PROJECT_DIR.mkdir(parents=True, exist_ok=True)
    up = _run([*COMPOSE, "up", "-d", "--wait"])
    if up.returncode != 0:
        pytest.fail(f"could not start the integration stack:\n{up.stderr}")
    try:
        yield
    finally:
        _run([*COMPOSE, "down", "-v"])
        shutil.rmtree(PROJECT_DIR, ignore_errors=True)


@pytest.fixture(scope="session", autouse=True)
def known_host(stack: None) -> Iterator[None]:
    """Register the container's host key for this session only, then forget it.

    The container's host key is regenerated every time it is recreated, so a
    `known_hosts` entry left over from a previous run would make this run
    fail with "REMOTE HOST IDENTIFICATION HAS CHANGED" - indistinguishable,
    from ssh's point of view, from a genuine man-in-the-middle. Scrubbing the
    entry both before (in case a previous run was interrupted before its own
    cleanup) and after keeps the developer's real `known_hosts` exactly as it
    was, with no residue either way.
    """
    known_hosts = Path.home() / ".ssh" / "known_hosts"
    known_hosts.parent.mkdir(parents=True, exist_ok=True)
    known_hosts.touch(exist_ok=True)
    _run(["ssh-keygen", "-R", REMOTE_HOST_ENTRY, "-f", str(known_hosts)])
    scan = _run(["ssh-keyscan", "-p", REMOTE_PORT, "-T", "5", "127.0.0.1"])
    if scan.returncode != 0 or not scan.stdout.strip():
        pytest.fail(f"could not scan the remote host key:\n{scan.stderr}")
    with known_hosts.open("a", encoding="utf-8") as handle:
        handle.write(scan.stdout)
    try:
        yield
    finally:
        _run(["ssh-keygen", "-R", REMOTE_HOST_ENTRY, "-f", str(known_hosts)])
